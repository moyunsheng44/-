def build_default_deck() -> list[UnitCard | SpellCard]:
    deck: list[UnitCard | SpellCard] = []
    for entry in CARD_LIBRARY:
        copies = entry["copies"]
        for _ in range(copies):
            if entry["card_type"] == "unit":
                deck.append(
                    UnitCard(
                        id=entry["id"],
                        name=entry["name"],
                        cost=entry["cost"],
                        card_type=entry["card_type"],
                        attack=entry["attack"],
                        health=entry["health"],
                        unit_class=entry["unit_class"],
                        action_cost=entry["action_cost"],
                        description=entry["description"],
                        emblem=entry["emblem"],
                        effects=[CardEffect(**e) for e in entry.get("effects", [])],
                    )
                )
            else:
                deck.append(
                    SpellCard(
                        id=entry["id"],
                        name=entry["name"],
                        cost=entry["cost"],
                        card_type=entry["card_type"],
                        effect_type=entry["effect_type"],
                        effect_value=entry["effect_value"],
                        target_type=entry["target_type"],
                        description=entry["description"],
                        emblem=entry["emblem"],
                    )
                )
    return deck
